GLYPH_W, GLYPH_H, SPACING = 5, 7, 1


class PixelFont:
    """Renders upper-case text; results are cached because HUD text repeats every frame."""

    def __init__(self):
        self.glyphs = {ch: [row for row in rows.split()] for ch, rows in _GLYPHS.items()}
        self._cache = {}

    def size(self, text, scale=1):
        n = len(text)
        return (max(0, n * (GLYPH_W + SPACING) - SPACING) * scale, GLYPH_H * scale)

    def render(self, text, color, scale=1, shadow=None):
        key = (text, color, scale, shadow)
        if key in self._cache:
            return self._cache[key]
        text = text.upper()
        w, h = self.size(text, scale)
        pad = max(1, scale // 2) if shadow else 0
        surf = pygame.Surface((w + pad, h + pad), pygame.SRCALPHA)
        layers = ((shadow, pad), (color, 0)) if shadow else ((color, 0),)
        for col, off in layers:
            for i, ch in enumerate(text):
                rows = self.glyphs.get(ch, self.glyphs["?"])
                gx = i * (GLYPH_W + SPACING) * scale + off
                for y, row in enumerate(rows):
                    for x, bit in enumerate(row):
                        if bit == "#":
                            surf.fill(col, (gx + x * scale, y * scale + off, scale, scale))
        if len(self._cache) > 256:
            self._cache.clear()
        self._cache[key] = surf
        return surf

    def draw(self, surf, text, pos, color, scale=1, shadow=None, center=False):
        img = self.render(text, color, scale, shadow)
        x, y = pos
        if center:
            x -= img.get_width() // 2
        surf.blit(img, (x, y))
        return img.get_rect(topleft=(x, y))
